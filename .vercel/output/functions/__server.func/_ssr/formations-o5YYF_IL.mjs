/** Rotate 180° so the away side faces the opposite goal. */
function slotsForSide(formation, side) {
	if (side === "home") return formation.slots;
	return formation.slots.map((s) => ({
		...s,
		x: 100 - s.x,
		y: 100 - s.y
	}));
}
